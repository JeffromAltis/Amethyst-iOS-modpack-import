/*
 * Amethyst-iOS: new class (absent from lwjgl-lwjglx.jar). LWJGL 2 KHRDebugCallback API implemented on LWJGL 3:
 * getPointer() returns the address of a GLDebugMessageCallback native stub that forwards to the Handler.
 * LWJGL 3's KHRDebug/GL43 cannot be given a glDebugMessageCallback(KHRDebugCallback) overload from here (they are
 * LWJGL 3 classes); callers can use getCallback() with glDebugMessageCallback(cb, 0L), or getPointer() with
 * nglDebugMessageCallback(ptr, 0L).
 */
package org.lwjgl.opengl;

import org.lwjgl.PointerWrapperAbstract;

/**
 * Instances of this class are needed to use the callback functionality of the KHR_debug extension.
 * Users of this class may provide implementations of the {@code Handler} interface to receive notifications.
 */
public final class KHRDebugCallback extends PointerWrapperAbstract {

	/** Severity levels. */
	private static final int
		GL_DEBUG_SEVERITY_HIGH         = 0x9146,
		GL_DEBUG_SEVERITY_MEDIUM       = 0x9147,
		GL_DEBUG_SEVERITY_LOW          = 0x9148,
		GL_DEBUG_SEVERITY_NOTIFICATION = 0x826B;

	/** Sources. */
	private static final int
		GL_DEBUG_SOURCE_API             = 0x8246,
		GL_DEBUG_SOURCE_WINDOW_SYSTEM   = 0x8247,
		GL_DEBUG_SOURCE_SHADER_COMPILER = 0x8248,
		GL_DEBUG_SOURCE_THIRD_PARTY     = 0x8249,
		GL_DEBUG_SOURCE_APPLICATION     = 0x824A,
		GL_DEBUG_SOURCE_OTHER           = 0x824B;

	/** Types. */
	private static final int
		GL_DEBUG_TYPE_ERROR               = 0x824C,
		GL_DEBUG_TYPE_DEPRECATED_BEHAVIOR = 0x824D,
		GL_DEBUG_TYPE_UNDEFINED_BEHAVIOR  = 0x824E,
		GL_DEBUG_TYPE_PORTABILITY         = 0x824F,
		GL_DEBUG_TYPE_PERFORMANCE         = 0x8250,
		GL_DEBUG_TYPE_OTHER               = 0x8251,
		GL_DEBUG_TYPE_MARKER              = 0x8268;

	private final Handler handler;
	private final GLDebugMessageCallback callback;

	/**
	 * Creates an KHRebugCallback with a default callback handler.
	 * The default handler will simply print the message on System.err.
	 */
	public KHRDebugCallback() {
		this(new Handler() {
			public void handleMessage(final int source, final int type, final int id, final int severity, final String message) {
				System.err.println("[LWJGL] KHR_debug message");
				System.err.println("\tID: " + id);

				String description;
				switch ( source ) {
					case GL_DEBUG_SOURCE_API:
						description = "API";
						break;
					case GL_DEBUG_SOURCE_WINDOW_SYSTEM:
						description = "WINDOW SYSTEM";
						break;
					case GL_DEBUG_SOURCE_SHADER_COMPILER:
						description = "SHADER COMPILER";
						break;
					case GL_DEBUG_SOURCE_THIRD_PARTY:
						description = "THIRD PARTY";
						break;
					case GL_DEBUG_SOURCE_APPLICATION:
						description = "APPLICATION";
						break;
					case GL_DEBUG_SOURCE_OTHER:
						description = "OTHER";
						break;
					default:
						description = printUnknownToken(source);
				}
				System.err.println("\tSource: " + description);

				switch ( type ) {
					case GL_DEBUG_TYPE_ERROR:
						description = "ERROR";
						break;
					case GL_DEBUG_TYPE_DEPRECATED_BEHAVIOR:
						description = "DEPRECATED BEHAVIOR";
						break;
					case GL_DEBUG_TYPE_UNDEFINED_BEHAVIOR:
						description = "UNDEFINED BEHAVIOR";
						break;
					case GL_DEBUG_TYPE_PORTABILITY:
						description = "PORTABILITY";
						break;
					case GL_DEBUG_TYPE_PERFORMANCE:
						description = "PERFORMANCE";
						break;
					case GL_DEBUG_TYPE_OTHER:
						description = "OTHER";
						break;
					case GL_DEBUG_TYPE_MARKER:
						description = "MARKER";
						break;
					default:
						description = printUnknownToken(type);
				}
				System.err.println("\tType: " + description);

				switch ( severity ) {
					case GL_DEBUG_SEVERITY_HIGH:
						description = "HIGH";
						break;
					case GL_DEBUG_SEVERITY_MEDIUM:
						description = "MEDIUM";
						break;
					case GL_DEBUG_SEVERITY_LOW:
						description = "LOW";
						break;
					case GL_DEBUG_SEVERITY_NOTIFICATION:
						description = "NOTIFICATION";
						break;
					default:
						description = printUnknownToken(severity);
				}
				System.err.println("\tSeverity: " + description);

				System.err.println("\tMessage: " + message);
			}

			private String printUnknownToken(final int token) {
				return "Unknown (0x" + Integer.toHexString(token).toUpperCase() + ")";
			}
		});
	}

	/**
	 * Creates an KHRDebugCallback with the specified callback handler.
	 * The handler's {@code handleMessage} method will be called whenever
	 * debug output is generated by the GL.
	 *
	 * @param handler the callback handler
	 */
	public KHRDebugCallback(final Handler handler) {
		this(handler, create(handler));
	}

	private KHRDebugCallback(final Handler handler, final GLDebugMessageCallback callback) {
		super(callback.address());

		this.handler = handler;
		this.callback = callback;
	}

	private static GLDebugMessageCallback create(final Handler handler) {
		return GLDebugMessageCallback.create(new GLDebugMessageCallbackI() {
			public void invoke(int source, int type, int id, int severity, int length, long message, long userParam) {
				synchronized ( handler ) {
					handler.handleMessage(source, type, id, severity, GLDebugMessageCallback.getMessage(length, message));
				}
			}
		});
	}

	Handler getHandler() {
		return handler;
	}

	/** Returns the LWJGL 3 callback wrapping the Handler, for use with {@code KHRDebug.glDebugMessageCallback(cb, 0L)}. */
	public GLDebugMessageCallback getCallback() {
		return callback;
	}

	/** Implementations of this interface can be used to receive KHR_debug notifications. */
	public interface Handler {

		/**
		 * This method will be called when an KHR_debug message is generated.
		 *
		 * @param source   the message source
		 * @param type     the message type
		 * @param id       the message ID
		 * @param severity the message severity
		 * @param message  the string representation of the message.
		 */
		void handleMessage(int source, int type, int id, int severity, String message);

	}

}
