/*
 * Amethyst-iOS: new class (absent from lwjgl-lwjglx.jar). LWJGL 2 AMDDebugOutputCallback API implemented on LWJGL 3:
 * getPointer() returns the address of a GLDebugMessageAMDCallback native stub that forwards to the Handler.
 * LWJGL 3's AMDDebugOutput cannot be given a glDebugMessageCallbackAMD(AMDDebugOutputCallback) overload from here (they are
 * LWJGL 3 classes); callers can use getCallback() with glDebugMessageCallbackAMD(cb, 0L), or getPointer() with
 * nglDebugMessageCallbackAMD(ptr, 0L).
 */
package org.lwjgl.opengl;

import org.lwjgl.PointerWrapperAbstract;

/**
 * Instances of this class are needed to use the callback functionality of the AMD_debug_output extension.
 * Users of this class may provide implementations of the {@code Handler} interface to receive notifications.
 */
public final class AMDDebugOutputCallback extends PointerWrapperAbstract {

	/** Severity levels. */
	private static final int GL_DEBUG_SEVERITY_HIGH_AMD = 0x9146,
		GL_DEBUG_SEVERITY_MEDIUM_AMD = 0x9147,
		GL_DEBUG_SEVERITY_LOW_AMD = 0x9148;

	/** Categories */
	private static final int GL_DEBUG_CATEGORY_API_ERROR_AMD = 0x9149,
		GL_DEBUG_CATEGORY_WINDOW_SYSTEM_AMD = 0x914A,
		GL_DEBUG_CATEGORY_DEPRECATION_AMD = 0x914B,
		GL_DEBUG_CATEGORY_UNDEFINED_BEHAVIOR_AMD = 0x914C,
		GL_DEBUG_CATEGORY_PERFORMANCE_AMD = 0x914D,
		GL_DEBUG_CATEGORY_SHADER_COMPILER_AMD = 0x914E,
		GL_DEBUG_CATEGORY_APPLICATION_AMD = 0x914F,
		GL_DEBUG_CATEGORY_OTHER_AMD = 0x9150;

	private final Handler handler;
	private final GLDebugMessageAMDCallback callback;

	/**
	 * Creates an AMD_debug_outputCallback with a default callback handler.
	 * The default handler will simply print the message on System.err.
	 */
	public AMDDebugOutputCallback() {
		this(new Handler() {
			public void handleMessage(final int id, final int category, final int severity, final String message) {
				System.err.println("[LWJGL] AMD_debug_output message");
				System.err.println("\tID: " + id);

				String description;
				switch ( category ) {
					case GL_DEBUG_CATEGORY_API_ERROR_AMD:
						description = "API ERROR";
						break;
					case GL_DEBUG_CATEGORY_WINDOW_SYSTEM_AMD:
						description = "WINDOW SYSTEM";
						break;
					case GL_DEBUG_CATEGORY_DEPRECATION_AMD:
						description = "DEPRECATION";
						break;
					case GL_DEBUG_CATEGORY_UNDEFINED_BEHAVIOR_AMD:
						description = "UNDEFINED BEHAVIOR";
						break;
					case GL_DEBUG_CATEGORY_PERFORMANCE_AMD:
						description = "PERFORMANCE";
						break;
					case GL_DEBUG_CATEGORY_SHADER_COMPILER_AMD:
						description = "SHADER COMPILER";
						break;
					case GL_DEBUG_CATEGORY_APPLICATION_AMD:
						description = "APPLICATION";
						break;
					case GL_DEBUG_CATEGORY_OTHER_AMD:
						description = "OTHER";
						break;
					default:
						description = printUnknownToken(category);
				}
				System.err.println("\tCategory: " + description);

				switch ( severity ) {
					case GL_DEBUG_SEVERITY_HIGH_AMD:
						description = "HIGH";
						break;
					case GL_DEBUG_SEVERITY_MEDIUM_AMD:
						description = "MEDIUM";
						break;
					case GL_DEBUG_SEVERITY_LOW_AMD:
						description = "LOW";
						break;
					default:
						description = printUnknownToken(severity);
				}
				System.err.println("\tSeverity: " + description);

				System.err.println("\tMessage: " + message);
			}

			private String printUnknownToken(final int token) {
				return "Unknown (0x" + Integer.toHexString(token).toUpperCase() + ")";
			}
		});
	}

	/**
	 * Creates an AMDDebugOutputCallback with the specified callback handler.
	 * The handler's {@code handleMessage} method will be called whenever
	 * debug output is generated by the GL.
	 *
	 * @param handler the callback handler
	 */
	public AMDDebugOutputCallback(final Handler handler) {
		this(handler, create(handler));
	}

	private AMDDebugOutputCallback(final Handler handler, final GLDebugMessageAMDCallback callback) {
		super(callback.address());

		this.handler = handler;
		this.callback = callback;
	}

	private static GLDebugMessageAMDCallback create(final Handler handler) {
		return GLDebugMessageAMDCallback.create(new GLDebugMessageAMDCallbackI() {
			public void invoke(int id, int category, int severity, int length, long message, long userParam) {
				synchronized ( handler ) {
					handler.handleMessage(id, category, severity, GLDebugMessageAMDCallback.getMessage(length, message));
				}
			}
		});
	}

	Handler getHandler() {
		return handler;
	}

	/** Returns the LWJGL 3 callback wrapping the Handler, for use with {@code AMDDebugOutput.glDebugMessageCallbackAMD(cb, 0L)}. */
	public GLDebugMessageAMDCallback getCallback() {
		return callback;
	}

	/** Implementations of this interface can be used to receive AMD_debug_output notifications. */
	public interface Handler {

		/**
		 * This method will be called when an AMD_debug_output message is generated.
		 *
		 * @param id       the message ID
		 * @param category the message category
		 * @param severity the message severity
		 * @param message  the string representation of the message.
		 */
		void handleMessage(int id, int category, int severity, String message);

	}

}
